"""Lean certificate draft emission.

Emits, per machine, a draft in the Dossier2RawTM generator style:
raw semantics header, the invariant statement, and the named closure
obligations the episode generators must fill. The draft contains
sorry markers by design; NONHALT is claimable only when the completed
file kernel-checks.
"""
import pathlib


TEMPLATE = """/-
Certificate draft: {code}
Generated by qgkit.bb6.decider (search untrusted; this file is the
trust surface once completed and kernel-checked).
Obligations: see manifest at end. Axiom budget: propext, Quot.sound.
-/

namespace QIG.Decider.{ns}

-- OBLIGATION O1 (generators): raw TM semantics + halt localization
-- for {code}, as in Dossier2RawTM sections 1-2.

-- OBLIGATION O2 (generators): record/episode theorems establishing
-- the abstract branch system below against raw dynamics.

{branch_comments}

{invariant_block}

-- OBLIGATION O3: invariant closure under every branch (statements
-- below; proofs by decide / omega per branch).

-- OBLIGATION O4: invariant excludes the fatal set; fatal states
-- halt (lethality); therefore the orbit never halts.

-- theorem nonhalting : Invariant blankOrbit -> ~ RawHalts blankStart
--   := sorry  -- closes after O1-O4

end QIG.Decider.{ns}

/- MANIFEST
{manifest}
-/
"""


def emit_draft(code, sys_, mono, cong, out_dir):
    ns = ''.join(ch for ch in code if ch.isalnum())[:16]
    bc = '\n'.join(
        f"-- branch {b.name}: x -> {b.matrix} * x + {b.offset}"
        for b in sys_.branches)
    inv_lines = []
    for coeffs, inc in mono:
        inv_lines.append(
            f"-- monotone functional f(x) = {coeffs} . x, "
            f"increment >= {inc} per step")
    for m, S in cong:
        inv_lines.append(
            f"-- congruence invariant mod {m}: {len(S)} residue "
            f"classes (closed, seed-containing, fatal-disjoint)")
    manifest = '\n'.join(
        ["O1 raw semantics", "O2 episode theorems",
         "O3 closure per branch x invariant",
         "O4 exclusion + lethality"])
    out = pathlib.Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    p = out / f"{ns}.lean.draft"
    p.write_text(TEMPLATE.format(code=code, ns=ns,
                                 branch_comments=bc,
                                 invariant_block='\n'.join(inv_lines),
                                 manifest=manifest))
    return str(p)
